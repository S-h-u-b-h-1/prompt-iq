import assert from 'node:assert/strict';
import { neon } from '@neondatabase/serverless';
import { ActivityRepository } from '../api/_src/repositories/ActivityRepository.js';
const host=process.argv[2];
const url=new URL(process.env.DATABASE_URL);
assert(host && host.endsWith('.neon.tech') && host.replace('-pooler','')!==url.hostname.replace('-pooler',''),'Provide an isolated Neon branch hostname, not production.');
url.hostname=host;
const sql=neon(url.toString());
const repo=new ActivityRepository(sql);
const fixture=crypto.randomUUID();
const accounts=await sql`INSERT INTO users(email,password_hash,plan) VALUES
  (${'activity-a-'+fixture+'@example.invalid'},'fixture-no-login','free'),
  (${'activity-b-'+fixture+'@example.invalid'},'fixture-no-login','free') RETURNING id`;
const [a,b]=accounts.map(row=>row.id);
const draft={kind:'draft',clientId:crypto.randomUUID(),text:'newest private draft',platform:'chatgpt',mode:'standard',revision:2};
assert.equal((await repo.preferences(a)).saveDrafts,false);
assert.equal((await repo.save(a,draft)).saved,false);
await repo.setPreferences(a,{saveDrafts:true,saveSearches:true,disclosureVersion:'2026-09-13-v2'});
assert.equal((await repo.save(a,draft)).saved,true);
assert.equal((await repo.save(a,{...draft,text:'stale',revision:1})).saved,false);
assert.equal((await repo.list(a,{limit:50,offset:0})).entries[0].text,draft.text);
assert.equal((await repo.list(b,{limit:50,offset:0})).entries.length,0);
const search={kind:'search',clientId:crypto.randomUUID(),text:'email',category:'all',resultCount:2};
assert.equal((await repo.save(a,search)).saved,true);
assert.equal((await repo.save(a,search)).saved,false);
const first=await repo.list(a,{limit:1,offset:0});
assert.equal(first.nextOffset,1);
assert.equal((await repo.list(a,{limit:1,offset:first.nextOffset})).entries.length,1);
await repo.setPreferences(a,{saveDrafts:false,saveSearches:false,disclosureVersion:'2026-09-13-v2'});
assert.equal((await repo.save(a,{...draft,revision:3})).saved,false);
await repo.clear(b);
assert.equal((await repo.list(a,{limit:50,offset:0})).entries.length,2,'Other account clear must not delete records');
await repo.clear(a);
assert.equal((await repo.list(a,{limit:50,offset:0})).entries.length,0);
assert.equal((await repo.preferences(a)).saveDrafts,false);
process.env.DATABASE_URL=url.toString();
process.env.JWT_SECRET=crypto.randomUUID();
const {default:handler}=await import('../api/history.js');
const {signToken}=await import('../api/_utils/auth-helper.js');
const call=async(user,method,action,body)=>{
  const req={method,query:action?{action}:{},headers:user?{authorization:'Bearer '+signToken({userId:user})}:{},body};
  const result={statusCode:0,body:null,headers:{}};
  const res={setHeader(k,v){result.headers[k]=v;},status(n){result.statusCode=n;return this;},json(v){result.body=v;return this;},end(){return this;}};
  await handler(req,res);return result;
};
assert.equal((await call(null,'GET','activity')).statusCode,401);
assert.equal((await call(a,'POST','activity',{...draft,clientId:'bad'})).statusCode,400);
assert.equal((await call(a,'POST','preferences',{saveDrafts:true,saveSearches:true,disclosureVersion:'2026-09-13-v2'})).statusCode,200);
assert.equal((await call(a,'POST','activity',{...draft,userId:b,revision:10})).body.saved,true);
assert.equal((await call(b,'GET','activity')).body.entries.length,0,'API must ignore a forged body userId');
const optimization={original:'Write a launch email',optimized:'Act as a marketer and write a launch email',scoreDelta:10,platform:'chatgpt',scoreOriginal:null,scoreOptimized:null,clientEventId:crypto.randomUUID(),engine:'smart_template'};
const one=await call(a,'POST',null,optimization);
const two=await call(a,'POST',null,optimization);
assert.equal(one.statusCode,200);
assert.equal(two.statusCode,200);
assert.equal(one.body.data.id,two.body.data.id,'Optimization retries must not duplicate');
assert.equal((await call(a,'GET',null)).body.length,1);
assert.equal((await call(b,'GET',null)).body.length,0);
const [expired]=await sql`UPDATE prompt_iq.drafts SET updated_at=now()-interval '31 days' WHERE user_id=${a} AND client_id=${draft.clientId}::uuid RETURNING client_id`;
assert(expired);
assert.equal((await repo.list(a,{limit:50,offset:0})).entries.length,0,'Expired entries must be removed');
assert.equal((await call(a,'DELETE','activity')).statusCode,200);
assert.equal((await call(a,'POST','activity',{...draft,revision:11})).body.saved,false,'Delete also revokes consent');
// Only fixture data is changed; these accounts disappear with the temporary branch.
console.log('Neon branch integration passed: API auth, forged-owner rejection, consent, revision ordering, optimization/search idempotency, isolation, pagination, retention, and deletion.');
